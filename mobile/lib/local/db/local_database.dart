/// Every connection, file or memory: foreign keys enforced (SQLite leaves them off by default) and WAL
/// journaling (ignored by in-memory databases). Top-level so it can run on the background isolate.
void configureConnection(Database raw) {
  raw.execute('PRAGMA foreign_keys = ON');
  raw.execute('PRAGMA journal_mode = WAL');
}

/// Current UTC time as epoch milliseconds, the storage format of every timestamp column (decision A151).
int utcNowMillis() => DateTime.now().toUtc().millisecondsSinceEpoch;

/// The standalone local database (SA2). Schema in `schema.drift`; persistence only, no business rules
/// (those are the SA3 services). Forward-only: a schema change bumps [schemaVersion] and adds a step
/// migration generated by `dart run drift_dev make-migrations`.
@DriftDatabase(
  include: {'schema.drift'},
  daos: [
    ProfileDao,
    MetaDao,
    GroupsDao,
    MembersDao,
    ExpensesDao,
    RevisionsDao,
    SettlementsDao,
    PaymentHandlesDao,
    IdempotencyDao,
    FuelPricesDao,
  ],
)
class LocalDatabase extends _$LocalDatabase {
  LocalDatabase(super.executor, {this._clock = utcNowMillis});

  /// A private in-memory database for tests.
  LocalDatabase.inMemory({int Function() clock = utcNowMillis})
      : this(NativeDatabase.memory(setup: configureConnection), clock: clock);

  /// The executor for a database file, opened on a background isolate.
  static QueryExecutor openFile(File file) => NativeDatabase.createInBackground(file, setup: configureConnection);

  final int Function() _clock;

  @override
  int get schemaVersion => 8;

  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (m) async {
          await m.createAll();
          await into(localMeta).insert(
            LocalMetaCompanion.insert(id: const Value(1), createdSchemaVersion: schemaVersion, createdAt: _clock()),
          );
        },
        // Forward-only (STANDALONE_SPEC 5.4): one step per shipped version, generated by drift_dev make-migrations.
        // SA15: every upgrade runs as ONE transaction with foreign keys off (drift's documented pattern for table
        // rebuilds; the pragma is a no-op inside a transaction, so it is set around it). A failing step, or a broken
        // reference found by foreign_key_check, rolls the whole upgrade back and the file stays at its old version.
        onUpgrade: (m, from, to) async {
          await customStatement('PRAGMA foreign_keys = OFF');
          try {
            await transaction(() async {
              await m.runMigrationSteps(from: from, to: to, steps: _steps);
              final broken = await customSelect('PRAGMA foreign_key_check').get();
              if (broken.isNotEmpty) {
                throw StateError('migration $from -> $to left ${broken.length} broken reference(s)');
              }
            });
          } finally {
            await customStatement('PRAGMA foreign_keys = ON');
          }
        },
        beforeOpen: (details) async {
          if (kDebugMode) {
            final broken = await customSelect('PRAGMA foreign_key_check').get();
            if (broken.isNotEmpty) throw StateError('foreign_key_check found ${broken.length} broken reference(s)');
          }
        },
      );

  static final _steps = migrationSteps(
          // SA5: the backup reminder can be snoozed (local_meta.backup_reminder_snoozed_until, nullable).
          from1To2: (m, schema) async {
            await m.addColumn(schema.localMeta, schema.localMeta.backupReminderSnoozedUntil);
          },
          // SA6: expense category (expenses.category, NOT NULL DEFAULT 'OTHER' + CHECK + index).
          from2To3: (m, schema) async {
            await m.addColumn(schema.expenses, schema.expenses.category);
            await m.createIndex(schema.ixExpensesGroupCategory);
          },
          // SA9: last-used reminder tone (local_meta.last_reminder_tone, nullable).
          from3To4: (m, schema) async {
            await m.addColumn(schema.localMeta, schema.localMeta.lastReminderTone);
          },
          // SA10: pool & treasurer, mirroring Java V20. Additive with defaults, so every existing row stays valid:
          // no treasurer, paid_from_pool 0, kind PAYMENT. Balances are unaffected (they never read these columns).
          from4To5: (m, schema) async {
            await m.addColumn(schema.expenseGroups, schema.expenseGroups.treasurerMemberId);
            await m.addColumn(schema.expenses, schema.expenses.paidFromPool);
            await m.addColumn(schema.settlements, schema.settlements.kind);
            await m.createIndex(schema.ixExpensesPool);
            await m.createIndex(schema.ixSettlementsDeposits);
            await m.createTrigger(schema.expenseGroupsTreasurerInsert);
            await m.createTrigger(schema.expenseGroupsTreasurerUpdate);
          },
          // SA11: saved fuel prices for the Khorouga calculator (new table, A168). Nothing existing changes.
          from5To6: (m, schema) async {
            await m.createTable(schema.fuelPrices);
          },
          // SA12: receipt-scan consent, daily counter and permission-error state (local_meta, all nullable or with
          // defaults, so every existing row stays valid).
          from6To7: (m, schema) async {
            await m.addColumn(schema.localMeta, schema.localMeta.ocrConsentAt);
            await m.addColumn(schema.localMeta, schema.localMeta.ocrScanDay);
            await m.addColumn(schema.localMeta, schema.localMeta.ocrScanCount);
            await m.addColumn(schema.localMeta, schema.localMeta.ocrPermissionErrors);
            await m.addColumn(schema.localMeta, schema.localMeta.ocrHiddenUntil);
          },
          // SA15: itemized v2, mirroring Java V21 (A171-A177). SQLite cannot drop the old table CHECKs (total
          // formula, breakdown formula) nor add a NOT NULL column without a constant default (unit_amount_minor), so
          // the three tables are rebuilt with drift's 12-step copy (indexes re-created). Every old row keeps its
          // meaning: items become quantity 1 with unit = amount; ITEMIZED expenses and their breakdown rows get
          // discount 0; nothing uses an amount form. owed_minor and expense_payers are copied unchanged, so balances
          // cannot move.
          from7To8: (m, schema) async {
            final e = schema.expenses;
            await m.alterTable(TableMigration(e, newColumns: [
              e.discountBps,
              e.discountAmountMinor,
              e.discountMinor,
              e.serviceAmountMinor,
              e.taxAmountMinor,
            ], columnTransformer: {
              e.discountMinor: const CustomExpression<int>("CASE WHEN split_type = 'ITEMIZED' THEN 0 END"),
            }));
            final s = schema.expenseSplits;
            await m.alterTable(TableMigration(s, newColumns: [
              s.discountMinor,
            ], columnTransformer: {
              s.discountMinor: const CustomExpression<int>('CASE WHEN items_minor IS NOT NULL THEN 0 END'),
            }));
            final i = schema.expenseItems;
            await m.alterTable(TableMigration(i, newColumns: [
              i.quantity,
              i.unitAmountMinor,
            ], columnTransformer: {
              i.unitAmountMinor: i.amountMinor,
            }));
          },
        );
}
