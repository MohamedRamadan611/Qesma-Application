/// Every connection, file or memory: foreign keys enforced (SQLite leaves them off by default) and WAL
/// journaling (ignored by in-memory databases). Top-level so it can run on the background isolate.
void configureConnection(Database raw) {
  raw.execute('PRAGMA foreign_keys = ON');
  raw.execute('PRAGMA journal_mode = WAL');
}

/// Current UTC time as epoch milliseconds, the storage format of every timestamp column (decision A151).
int utcNowMillis() => DateTime.now().toUtc().millisecondsSinceEpoch;

/// The standalone local database (SA2). Schema in `schema.drift`; persistence only, no business rules
/// (those are the SA3 services). Forward-only: a schema change bumps [schemaVersion] and adds a step
/// migration generated by `dart run drift_dev make-migrations`.
@DriftDatabase(
  include: {'schema.drift'},
  daos: [
    ProfileDao,
    MetaDao,
    GroupsDao,
    MembersDao,
    ExpensesDao,
    RevisionsDao,
    SettlementsDao,
    PaymentHandlesDao,
    IdempotencyDao,
  ],
)
class LocalDatabase extends _$LocalDatabase {
  LocalDatabase(super.executor, {this._clock = utcNowMillis});

  /// A private in-memory database for tests.
  LocalDatabase.inMemory({int Function() clock = utcNowMillis})
      : this(NativeDatabase.memory(setup: configureConnection), clock: clock);

  /// The executor for a database file, opened on a background isolate.
  static QueryExecutor openFile(File file) => NativeDatabase.createInBackground(file, setup: configureConnection);

  final int Function() _clock;

  @override
  int get schemaVersion => 3;

  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (m) async {
          await m.createAll();
          await into(localMeta).insert(
            LocalMetaCompanion.insert(id: const Value(1), createdSchemaVersion: schemaVersion, createdAt: _clock()),
          );
        },
        // Forward-only (STANDALONE_SPEC 5.4): one step per shipped version, generated by drift_dev make-migrations.
        onUpgrade: stepByStep(
          // SA5: the backup reminder can be snoozed (local_meta.backup_reminder_snoozed_until, nullable).
          from1To2: (m, schema) async {
            await m.addColumn(schema.localMeta, schema.localMeta.backupReminderSnoozedUntil);
          },
          // SA6: expense category (expenses.category, NOT NULL DEFAULT 'OTHER' + CHECK + index).
          from2To3: (m, schema) async {
            await m.addColumn(schema.expenses, schema.expenses.category);
            await m.createIndex(schema.ixExpensesGroupCategory);
          },
        ),
        beforeOpen: (details) async {
          if (kDebugMode) {
            final broken = await customSelect('PRAGMA foreign_key_check').get();
            if (broken.isNotEmpty) throw StateError('foreign_key_check found ${broken.length} broken reference(s)');
          }
        },
      );
}
